# actionsFilePatterns = [".github/workflows/**/*.y*ml"]
# k8sFilePatterns = [
#   "**/*.{deployment,service,statefulset,daemonset,cronjob,job,configmap,secret,ingress,pvc}.y*ml",
#   "**/k8s/**/*.y*ml",
#   "**/kubernetes/**/*.y*ml",
#   "**/manifests/**/*.y*ml",
#   "**/deploy/**/*.y*ml"
# ]
