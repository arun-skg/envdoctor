use crate::config::EnvdoctorConfig;
use crate::models::VariableType;

/// Infer a validation schema for every known environment variable by inspecting
/// existing env values and source-code usage patterns, then emit it as a
/// TypeScript module (`envdoctor.schema.ts`). Mirrors the TS `generateSchema`.
///
///   - parseInt(process.env.PORT)     → integer
///   - Number(process.env.RATIO)      → float
///   - process.env.DEBUG === "true"   → boolean
///   - JSON.parse(process.env.CONFIG) → json
///   - process.env.API_URL            → string (dropped; nothing to assert)
pub fn generate_variable_schema_ts(model: &crate::models::ProjectModel) -> String {
    // name → type string (e.g. "integer")
    let mut schema: std::collections::BTreeMap<String, String> = std::collections::BTreeMap::new();

    // Infer from existing env values first.
    for file in &model.env_files {
        for v in &file.variables {
            let Some(value) = &v.value else { continue };
            if let Some(mapped) = map_inferred_type(crate::utils::type_infer::infer_type(Some(value)))
            {
                schema.insert(v.name.clone(), mapped.to_string());
            }
        }
    }

    // Refine from source usage patterns.
    for file in &model.source_files {
        let Ok(content) = std::fs::read_to_string(&file.file_path) else {
            continue;
        };
        let lines: Vec<&str> = content.split('\n').collect();
        for usage in &file.usages {
            for origin in &usage.origins {
                let Some(line_no) = origin.line else { continue };
                let line = lines.get(line_no.saturating_sub(1)).copied().unwrap_or("");
                if let Some(inferred) = infer_from_line(&usage.name, line) {
                    schema.insert(usage.name.clone(), inferred.to_string());
                }
            }
        }
    }

    if schema.is_empty() {
        return "// Generated by envdoctor. No schema could be inferred.\nexport default {\n  schema: {},\n};\n".to_string();
    }

    let mut lines: Vec<String> = Vec::new();
    lines.push("// Generated by envdoctor. Merge into envdoctor.config.ts:".to_string());
    lines.push(
        "// import schema from './envdoctor.schema'; export default { ..., ...schema };".to_string(),
    );
    lines.push(String::new());
    lines.push("export default {".to_string());
    lines.push("  schema: {".to_string());
    for (name, ty) in &schema {
        lines.push(format!("    {name}: {{ type: \"{ty}\" }},"));
    }
    lines.push("  },".to_string());
    lines.push("};".to_string());
    lines.push(String::new());
    lines.join("\n")
}

/// Map an inferred variable type onto a schema type, dropping `string`/`unknown`
/// (nothing worth asserting).
fn map_inferred_type(ty: VariableType) -> Option<&'static str> {
    match ty {
        VariableType::Integer => Some("integer"),
        VariableType::Float => Some("float"),
        VariableType::Boolean => Some("boolean"),
        VariableType::Url => Some("url"),
        VariableType::Json => Some("json"),
        VariableType::String | VariableType::Unknown => None,
    }
}

/// Infer a schema type from a single source line's access pattern.
fn infer_from_line(name: &str, line: &str) -> Option<&'static str> {
    let escaped = regex::escape(name);
    let access = format!(r"process\.env\.{escaped}|import\.meta\.env\.{escaped}");

    let int_re = regex::Regex::new(&format!(r"(parseInt|Number\.parseInt)\s*\(\s*({access})")).unwrap();
    if int_re.is_match(line) {
        return Some("integer");
    }
    let float_re = regex::Regex::new(&format!(
        r"(Number\s*\(\s*({access})\s*\)|parseFloat|Number\.parseFloat)\s*\(\s*({access})"
    ))
    .unwrap();
    if float_re.is_match(line) {
        return Some("float");
    }
    let bool_re = regex::Regex::new(&format!(
        r#"({access})\s*===?\s*["']true["']|({access})\s*===?\s*["']false["']|Boolean\s*\(\s*({access})"#
    ))
    .unwrap();
    if bool_re.is_match(line) {
        return Some("boolean");
    }
    let json_re = regex::Regex::new(&format!(r"JSON\.parse\s*\(\s*({access})")).unwrap();
    if json_re.is_match(line) {
        return Some("json");
    }
    None
}

