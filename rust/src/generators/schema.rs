/// Generate a schema.json file from the config's variable schemas.
pub fn generate_variable_schema_json(config: &EnvdoctorConfig) -> String {
    if config.schema.is_empty() {
        return "{}".to_string();
    }

    let mut map = serde_json::Map::new();
    for (name, schema) in &config.schema {
        let mut obj = serde_json::Map::new();
        if let Some(t) = &schema.var_type {
            obj.insert("type".to_string(), serde_json::json!(format!("{:?}", t).to_lowercase()));
        }
        if let Some(opt) = schema.optional {
            obj.insert("optional".to_string(), serde_json::json!(opt));
        }
        if let Some(enums) = &schema.enum_values {
            obj.insert("enum".to_string(), serde_json::json!(enums));
        }
        if let Some(regex) = &schema.regex {
            obj.insert("pattern".to_string(), serde_json::json!(regex));
        }
        if let Some(min) = schema.min {
            obj.insert("minimum".to_string(), serde_json::json!(min));
        }
        if let Some(max) = schema.max {
            obj.insert("maximum".to_string(), serde_json::json!(max));
        }
        map.insert(name.clone(), serde_json::Value::Object(obj));
    }

    serde_json::to_string_pretty(&serde_json::Value::Object(map)).unwrap()
}